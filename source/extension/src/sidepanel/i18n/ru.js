/** Строка по ключу; незнакомый ключ возвращается как есть. */
export function t(key, params) {
  const raw = Object.prototype.hasOwnProperty.call(ru, key) ? ru[key] : key;
  if (!params) return raw;
  return raw.replace(/\{(\w+)\}/g, (match, name) => (params[name] === undefined || params[name] === null ? match : String(params[name])));
}
