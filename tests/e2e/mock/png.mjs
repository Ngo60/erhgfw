// Deterministic test images: generated PNGs plus small embedded JPEG/WebP fixtures (all valid, Chrome-decodable).
import zlib from 'node:zlib';

const PNG_SIGNATURE = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);

let crcTable;
function crc32(buf) {
  if (typeof zlib.crc32 === 'function') return zlib.crc32(buf) >>> 0;
  if (!crcTable) {
    crcTable = new Uint32Array(256);
    for (let n = 0; n < 256; n++) {
      let c = n;
      for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
      crcTable[n] = c >>> 0;
    }
  }
  let c = 0xffffffff;
  for (let i = 0; i < buf.length; i++) c = crcTable[(c ^ buf[i]) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

function pngChunk(type, data) {
  const body = Buffer.concat([Buffer.from(type, 'latin1'), data]);
  const out = Buffer.alloc(body.length + 8);
  out.writeUInt32BE(data.length, 0);
  body.copy(out, 4);
  out.writeUInt32BE(crc32(body), body.length + 4);
  return out;
}

function hashSeed(seed) {
  const s = String(seed);
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return h >>> 0;
}

// mulberry32
function prng(state) {
  let a = state >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/**
 * 8-bit RGB PNG filled with a pseudo-random coloured block pattern derived from `seed`.
 * Same arguments -> same bytes; different seeds -> different bytes.
 * @param {{width?: number, height?: number, seed?: string|number}} [opts]
 * @returns {Buffer}
 */
export function makePng({ width = 768, height = 768, seed = 0 } = {}) {
  for (const [name, v] of [['width', width], ['height', height]]) {
    if (!Number.isInteger(v) || v < 1 || v > 16384) throw new RangeError(`makePng: bad ${name}: ${v}`);
  }
  const rnd = prng(hashSeed(seed) ^ Math.imul(width, 73856093) ^ Math.imul(height, 19349663));
  const block = Math.max(4, Math.round(Math.max(width, height) / 96));
  const stride = width * 3 + 1;
  const raw = Buffer.alloc(stride * height); // filter byte 0 (None) per scanline is already zero
  const blocksPerRow = Math.ceil(width / block);
  for (let by = 0; by * block < height; by++) {
    const first = by * block * stride;
    const colours = new Uint8Array(blocksPerRow * 3);
    for (let i = 0; i < colours.length; i++) colours[i] = (rnd() * 256) | 0;
    for (let x = 0; x < width; x++) {
      const c = ((x / block) | 0) * 3;
      const o = first + 1 + x * 3;
      raw[o] = colours[c];
      raw[o + 1] = colours[c + 1];
      raw[o + 2] = colours[c + 2];
    }
    const lastRow = Math.min(height, (by + 1) * block);
    for (let y = by * block + 1; y < lastRow; y++) raw.copy(raw, y * stride, first, first + stride);
  }
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(width, 0);
  ihdr.writeUInt32BE(height, 4);
  ihdr[8] = 8; // bit depth
  ihdr[9] = 2; // colour type: RGB
  return Buffer.concat([
    PNG_SIGNATURE,
    pngChunk('IHDR', ihdr),
    pngChunk('IDAT', zlib.deflateSync(raw, { level: 6 })),
    pngChunk('IEND', Buffer.alloc(0)),
  ]);
}

const FIXTURE_SIZE = 768;

// Inserting a COM segment after the APPn markers keeps the file a valid JPEG while changing its bytes.
function jpegWithComment(base, text) {
  let i = 2;
  while (base[i] === 0xff && base[i + 1] >= 0xe0 && base[i + 1] <= 0xef) i += 2 + base.readUInt16BE(i + 2);
  const payload = Buffer.from(text, 'latin1');
  const seg = Buffer.alloc(4 + payload.length);
  seg[0] = 0xff;
  seg[1] = 0xfe;
  seg.writeUInt16BE(2 + payload.length, 2);
  payload.copy(seg, 4);
  return Buffer.concat([base.subarray(0, i), seg, base.subarray(i)]);
}

// The fixture is an extended-format (VP8X) file, so an extra unknown trailing chunk stays valid.
function webpWithChunk(base, text) {
  const payload = Buffer.from(text, 'latin1');
  const pad = payload.length & 1;
  const chunk = Buffer.alloc(8 + payload.length + pad);
  chunk.write('SEED', 0, 'latin1');
  chunk.writeUInt32LE(payload.length, 4);
  payload.copy(chunk, 8);
  const out = Buffer.concat([base, chunk]);
  out.writeUInt32LE(out.length - 8, 4);
  return out;
}

/**
 * Valid 768x768 baseline JPEG. A defined `seed` adds a comment segment so repeated calls can yield distinct bytes.
 * @param {{seed?: string|number}} [opts]
 */
export function makeJpeg({ seed } = {}) {
  const base = Buffer.from(JPEG_B64, 'base64');
  const buffer = seed === undefined ? base : jpegWithComment(base, `seed:${seed}`);
  return { buffer, width: FIXTURE_SIZE, height: FIXTURE_SIZE, contentType: 'image/jpeg', ext: 'jpg' };
}

/**
 * Valid 768x768 lossy WebP (VP8X + ICCP + VP8). A defined `seed` appends an unknown chunk for distinct bytes.
 * @param {{seed?: string|number}} [opts]
 */
export function makeWebp({ seed } = {}) {
  const base = Buffer.from(WEBP_B64, 'base64');
  const buffer = seed === undefined ? base : webpWithChunk(base, `seed:${seed}`);
  return { buffer, width: FIXTURE_SIZE, height: FIXTURE_SIZE, contentType: 'image/webp', ext: 'webp' };
}

